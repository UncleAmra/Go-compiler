#ifndef MINIGO_TOKEN_H
#define MINIGO_TOKEN_H

#include "minigo/common.h"

typedef enum {
    /* Special tokens */
    TOKEN_EOF = 0,
    TOKEN_ILLEGAL,

    /* Literals & Identifiers */
    TOKEN_IDENT,
    TOKEN_INT_LIT,
    TOKEN_FLOAT_LIT,
    TOKEN_STRING_LIT,

    /* Keywords */
    TOKEN_PACKAGE,
    TOKEN_IMPORT,
    TOKEN_FUNC,
    TOKEN_VAR,
    TOKEN_CONST,
    TOKEN_TYPE,
    TOKEN_STRUCT,
    TOKEN_RETURN,
    TOKEN_IF,
    TOKEN_ELSE,
    TOKEN_FOR,
    TOKEN_BREAK,
    TOKEN_CONTINUE,

    /* Operators */
    TOKEN_PLUS,          /* + */
    TOKEN_MINUS,         /* - */
    TOKEN_STAR,          /* * */
    TOKEN_SLASH,         /* / */
    TOKEN_PERCENT,       /* % */
    TOKEN_AMP,           /* & */
    TOKEN_PIPE,          /* | */
    TOKEN_CARET,         /* ^ */
    TOKEN_SHL,           /* << */
    TOKEN_SHR,           /* >> */
    TOKEN_AND_AND,       /* && */
    TOKEN_OR_OR,         /* || */
    TOKEN_EQ_EQ,         /* == */
    TOKEN_NOT_EQ,        /* != */
    TOKEN_LT,            /* < */
    TOKEN_LE,            /* <= */
    TOKEN_GT,            /* > */
    TOKEN_GE,            /* >= */
    TOKEN_EXCLAMATION,   /* ! */
    TOKEN_COLON_ASSIGN,  /* := */
    TOKEN_ASSIGN,        /* = */
    TOKEN_PLUS_ASSIGN,   /* += */
    TOKEN_MINUS_ASSIGN,  /* -= */
    TOKEN_INC,           /* ++ */
    TOKEN_DEC,           /* -- */

    /* Delimiters */
    TOKEN_LPAREN,        /* ( */
    TOKEN_RPAREN,        /* ) */
    TOKEN_LBRACE,        /* { */
    TOKEN_RBRACE,        /* } */
    TOKEN_LBRACKET,      /* [ */
    TOKEN_RBRACKET,      /* ] */
    TOKEN_COMMA,         /* , */
    TOKEN_DOT,           /* . */
    TOKEN_SEMICOLON,     /* ; (explicit or auto-inserted) */
    TOKEN_COLON          /* : */
} TokenType;

typedef struct {
    TokenType type;
    const char *start;
    size_t length;
    SourcePos pos;
    bool is_auto_semicolon; /* True if generated by Automatic Semicolon Insertion */
    union {
        int64_t int_val;
        double float_val;
    };
} Token;

const char *token_type_name(TokenType type);
void token_print(const Token *tok);

#endif /* MINIGO_TOKEN_H */
